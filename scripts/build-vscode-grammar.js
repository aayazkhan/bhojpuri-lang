#!/usr/bin/env node
// Builds editors/vscode/syntaxes/bhojpuri.tmLanguage.json from the keyword tables in
// src/keywords.js, so renaming a keyword there renames it in VS Code too.
//
//   node scripts/build-vscode-grammar.js          write the file
//   node scripts/build-vscode-grammar.js --check  exit 1 if the file is out of date (used by the tests)

import { readFileSync, writeFileSync } from "node:fs";
import { KEYWORDS, LOOP_WORDS, BUILTINS } from "../src/keywords.js";

const OUTPUT = new URL("../editors/vscode/syntaxes/bhojpuri.tmLanguage.json", import.meta.url);

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// "na ta jadi" matches with any spaces or tabs between the words, like the tokenizer.
const keywordPattern = (text) => text.trim().split(/\s+/).map(escapeRegex).join("[ \\t]+");
// Longest first, so "na ta jadi" wins over "na ta".
const alternatives = (texts) => [...texts].sort((a, b) => b.length - a.length).map(keywordPattern).join("|");
const NAME_END = "(?![\\p{L}\\p{M}\\p{N}_])";
const words = (ids) => alternatives(ids.map((id) => KEYWORDS[id]));

const CONTROL = ["IF", "ELSE_IF", "ELSE", "WHILE", "BREAK", "CONTINUE", "RETURN", "TRY", "CATCH", "THROW"];
const IMPORT = ["IMPORT"];
const LITERALS = ["TRUE", "FALSE", "NULL"];
const PROGRAM = ["PROGRAM_START", "PROGRAM_END"];
const OTHER = Object.keys(KEYWORDS).filter(
  (id) => ![...CONTROL, ...IMPORT, ...LITERALS, ...PROGRAM, "FOR", "LET", "FUNCTION", "PRINT"].includes(id),
);
if (OTHER.length) throw new Error(`Give these keywords a colour in build-vscode-grammar.js: ${OTHER.join(", ")}`);

export function buildGrammar() {
  return {
    $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    name: "Bhojpuri Lang",
    scopeName: "source.bhojpuri",
    comment: "Generated by scripts/build-vscode-grammar.js from src/keywords.js. Don't edit by hand.",
    patterns: [{ include: "#code" }],
    repository: {
      code: {
        patterns: [
          { include: "#comments" },
          { include: "#strings" },
          { include: "#loop-header" },
          { include: "#function-definition" },
          { include: "#keywords" },
          { include: "#numbers" },
          { include: "#builtins" },
          { include: "#braces" },
        ],
      },
      comments: {
        patterns: [
          { name: "comment.line.double-slash.bhojpuri", match: "//.*$" },
          { name: "comment.block.bhojpuri", begin: "/\\*", end: "\\*/" },
        ],
      },
      strings: {
        patterns: [
          { name: "string.quoted.double.bhojpuri", begin: '"', end: '"|$', patterns: [{ include: "#escapes" }] },
          { name: "string.quoted.single.bhojpuri", begin: "'", end: "'|$", patterns: [{ include: "#escapes" }] },
          {
            name: "string.template.bhojpuri",
            begin: "`",
            end: "`|$",
            patterns: [
              { include: "#escapes" },
              {
                name: "meta.embedded.expression.bhojpuri",
                begin: "\\{",
                end: "\\}",
                beginCaptures: { 0: { name: "punctuation.section.embedded.begin.bhojpuri" } },
                endCaptures: { 0: { name: "punctuation.section.embedded.end.bhojpuri" } },
                contentName: "source.bhojpuri",
                patterns: [{ include: "#code" }],
              },
            ],
          },
        ],
      },
      escapes: { name: "constant.character.escape.bhojpuri", match: "\\\\." },
      // Keeps braces balanced inside a template string's {…}, e.g. {{ "k": 1 }["k"]}.
      braces: { begin: "\\{", end: "\\}", patterns: [{ include: "#code" }] },
      // `se`, `tak`, `kadam` and `me` are only special between `har` and its `{`.
      "loop-header": {
        begin: `(?<![\\p{L}\\p{M}\\p{N}_])(${keywordPattern(KEYWORDS.FOR)})${NAME_END}`,
        end: "(?=\\{)",
        beginCaptures: { 1: { name: "keyword.control.loop.bhojpuri" } },
        patterns: [
          { include: "#comments" },
          { include: "#strings" },
          {
            name: "keyword.control.loop.bhojpuri",
            match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${alternatives(Object.values(LOOP_WORDS))})${NAME_END}`,
          },
          { include: "#keywords" },
          { include: "#numbers" },
          { include: "#builtins" },
        ],
      },
      "function-definition": {
        match: `(?<![\\p{L}\\p{M}\\p{N}_])(${keywordPattern(KEYWORDS.FUNCTION)})[ \\t]+([\\p{L}_][\\p{L}\\p{M}\\p{N}_]*)`,
        captures: {
          1: { name: "storage.type.function.bhojpuri" },
          2: { name: "entity.name.function.bhojpuri" },
        },
      },
      keywords: {
        patterns: [
          { name: "keyword.control.bhojpuri", match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${words(CONTROL)})${NAME_END}` },
          { name: "keyword.other.program.bhojpuri", match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${words(PROGRAM)})${NAME_END}` },
          { name: "storage.type.bhojpuri", match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${words(["LET", "FUNCTION"])})${NAME_END}` },
          { name: "keyword.control.import.bhojpuri", match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${words(IMPORT)})${NAME_END}` },
          { name: "keyword.other.print.bhojpuri", match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${words(["PRINT"])})${NAME_END}` },
          { name: "constant.language.bhojpuri", match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${words(LITERALS)})${NAME_END}` },
        ],
      },
      numbers: { name: "constant.numeric.bhojpuri", match: "(?<![\\p{L}\\p{M}\\p{N}_])\\d+(?:\\.\\d+)?" },
      // Built-ins are coloured only when called, since the names can be reused for variables.
      builtins: {
        name: "support.function.builtin.bhojpuri",
        match: `(?<![\\p{L}\\p{M}\\p{N}_])(?:${alternatives(Object.values(BUILTINS))})(?=\\s*\\()`,
      },
    },
  };
}

const text = JSON.stringify(buildGrammar(), null, 2) + "\n";

if (process.argv[1] === new URL(import.meta.url).pathname) {
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {}
    if (current !== text) {
      console.error("editors/vscode/syntaxes/bhojpuri.tmLanguage.json is out of date. Run: node scripts/build-vscode-grammar.js");
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, text);
    console.log("Wrote editors/vscode/syntaxes/bhojpuri.tmLanguage.json");
  }
}

export { text as grammarText };
